#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>
#include <stdlib.h>   /* qsort */
#include <string.h>   /* memcmp、strcmp */

/* ============================================================
 * 题目：模仿 qsort，实现一个能排任意类型数据的通用冒泡排序
 * ------------------------------------------------------------
 * 普通冒泡排序只能排某一种类型：
 *     void bubble(int arr[], int n)           —— 只能排 int
 *     void bubble_double(double arr[], ...)   —— 只能排 double
 * 换一种类型就得把整个函数重抄一遍，逻辑一模一样，
 * 只是数据类型不同——这是非常低级的重复劳动。
 *
 * qsort 的解决办法是：把"排序函数不知道的东西"全部变成参数传进来。
 *   - 数组从哪开始（首元素地址）
 *   - 一共有多少个元素
 *   - 每个元素占多少字节
 *   - 两个元素之间"怎么比大小"（回调函数）
 * 于是排序逻辑只写一次，就能排 int、double、结构体、字符串……
 *
 * 本文件就是用冒泡排序的骨架，复刻 qsort 的这套通用设计。
 * ============================================================ */

/* ------------------------------------------------------------
 * 先认识 qsort 的四个参数（bubble_sort 完全照抄这套设计）：
 *
 *   void *base
 *       数组首元素的地址。
 *       为什么用 void*？因为 void* 是"无类型指针"，
 *       int*、double*、Student* 都可以隐式转成 void*，
 *       这样任意类型的数组都能传进来。
 *       代价是：void* 不能直接解引用、不能做指针加减，
 *       因为编译器不知道它指向的东西"一步"跨几个字节。
 *
 *   size_t nmemb          (number of members)
 *       元素个数。size_t 是专门表示"大小/个数"的无符号整型
 *       （32 位下是 unsigned int，64 位下是 unsigned long long），
 *       用来存元素个数不会出现负数，比 int 更稳妥。
 *
 *   size_t size
 *       单个元素占多少字节，调用时一般传 sizeof(arr[0])。
 *       有了它，排序函数才能靠"地址 = 首地址 + 下标 × size"
 *       计算出任意一个元素的地址。
 *
 *   int (*cmp)(const void *, const void *)
 *       函数指针，指向"比较函数"。
 *       调用者把自己写的比较函数传进来，排序过程中反复回调它。
 *
 *       函数指针的语法拆解（这是新手最容易晕的地方）：
 *           int  (*cmp)  (const void *, const void *)
 *           │    │ │     │
 *           │    │ └── 参数列表：两个 void* 参数
 *           │    └──── cmp 是指针，"*"说明它先和括号结合
 *           └───────── 返回类型：int
 *       如果写成 int *cmp(...)，意思就变成"返回 int* 的函数"了，
 *       括号的位置决定了它到底是"函数指针"还是"返回指针的函数"。
 *
 *       比较函数的返回值约定（和 qsort 一模一样）：
 *           返回 < 0 —— 第一个参数应该排在前面
 *           返回 = 0 —— 两者相等，谁的顺序都行
 *           返回 > 0 —— 第一个参数应该排在后面
 *       升序就按 (a>b)-(a<b) 来写；
 *       想改成降序，只需要在比较函数里把 a、b 反过来比，
 *       排序函数本身一个字都不用动——这就是回调的威力。
 * ------------------------------------------------------------ */

/* ------------------------------------------------------------
 * 比较函数（int 版）
 *
 * 参数统一用 const void*，是为了匹配函数指针的类型；
 * 加 const 的两层意思：
 *   1) 比较只是"看一眼"，不应该修改原数据；
 *   2) 签名和三方函数（qsort 等）要求的格式一致，可以直接复用。
 *
 * 为什么不直接写 return *(int*)a - *(int*)b ？
 *   两个大 int 相减可能溢出 int：
 *   比如 2000000000 - (-2000000000) = 4000000000，超出 int 上限，
 *   结果会翻转成负数，排序顺序就悄悄出错了。
 *   (x > y) - (x < y) 的结果只可能是 1、0、-1，永远不会溢出。
 * ------------------------------------------------------------ */
int cmp_int(const void *a, const void *b)
{
	/* void* 不能直接解引用：
	 * 先强制转回 const int*，再用 * 取出里面的 int 值。 */
	int x = *(const int *)a;
	int y = *(const int *)b;

	/* 不用 if 分支的写法，效果等价于：
	 *   if (x > y) return 1;
	 *   else if (x < y) return -1;
	 *   else return 0;
	 * 原理：比较表达式成立得 1、不成立得 0，两个式子相减正好得到 1/0/-1。
	 * 写成一行更简洁，编译器也更容易优化 */
	return (x > y) - (x < y);
}

/* ------------------------------------------------------------
 * 通用冒泡排序（模仿 qsort）
 *   base  : 待排序数组的首元素地址
 *   nmemb : 元素个数
 *   size  : 单个元素的字节数
 *   cmp   : 比较函数指针，用法和 qsort 完全一样
 *
 * 和普通冒泡排序的唯一区别：
 * 比较和交换都不知道元素类型，全靠"字节地址 + 字节拷贝"完成。
 * ------------------------------------------------------------ */
void bubble_sort(void *base, size_t nmemb, size_t size,
	int (*cmp)(const void *a, const void *b))
{
	/* void* 不能直接做加减运算（编译器不知道"一步"跨多远），
	 * 必须先转成具体类型的指针。转成 char* 是因为 char 固定占
	 * 1 个字节，"一步"正好 1 字节，想跳多少字节就加多少个 1。
	 * 这就把数组看成了一串没有意义的字节，正是"通用"的关键。 */
	char *p = (char *)base;

	size_t i, j, k;   /* i：第几趟；j：本趟比到第几个；
	                     k：交换时数到第几个字节 */
	int swapped;      /* 本趟有没有发生过交换：1 有，0 没有 */

	/* 防御性检查：
	 *   base 为空  —— 没东西可排；
	 *   cmp 为空   —— 没法比较大小；
	 *   nmemb < 2  —— 0 个或 1 个元素，本来就"有序"。
	 * 任何一个成立就原地返回，避免后面空指针解引用。 */
	if (base == NULL || cmp == NULL || nmemb < 2)
	{
		return;
	}

	/* 外层循环：最多冒 nmemb-1 趟。
	 * 为什么是 nmemb-1 趟？
	 * 每一趟都会把"当前范围内的最大值"像泡泡一样冒到末尾并固定，
	 * nmemb-1 个元素就位之后，剩下最后一个自然就在它该在的位置。 */
	for (i = 0; i < nmemb - 1; i++)
	{
		swapped = 0;   /* 每趟开始先假设"本趟没有发生任何交换" */

		/* 内层循环：相邻元素两两比较。
		 * 范围 0 ~ nmemb-2-i：
		 *   -1  ：因为要访问 j+1，j 最多到 nmemb-2，否则越界；
		 *   -i  ：末尾 i 个元素已经在之前的趟里排好，
		 *         每完成一趟就多固定一个，所以每趟少比一个。 */
		for (j = 0; j < nmemb - 1 - i; j++)
		{
			/* 计算第 j 个和第 j+1 个元素的首地址：
			 *   第 j 个元素 = p 往后跳 j 个"size 字节"。
			 * 以 int 数组（size = 4）为例：
			 *   p        → 元素 0，字节偏移 0
			 *   p + 1*4  → 元素 1，字节偏移 4
			 *   p + 2*4  → 元素 2，字节偏移 8
			 * 注意不能写 p + j（那只是加 j 个字节，不是 j 个元素）。 */
			char *left = p + j * size;
			char *right = p + (j + 1) * size;

			/* 把两个元素的首地址交给回调函数 cmp。
			 * cmp 内部会自己转回正确的类型再解引用，
			 * 排序函数这边只负责"递地址"，完全不关心元素是什么。 */
			if (cmp(left, right) > 0)   /* >0 表示 left 大于 right，要换 */
			{
				/* 交换两个元素。
				 * 不知道元素是什么类型，也不知道元素多大，
				 * 但知道"它占 size 个字节"——那就一个字节一个字节地换：
				 * 循环 size 次，把两个元素逐字节对调，
				 * 全部换完，整个元素就完整地交换了。
				 * 这是本函数最巧妙的地方：
				 * 不管元素是 4 字节的 int，还是几百字节的结构体，
				 * 这段交换代码都是同一个循环，一个字都不用改。 */
				for (k = 0; k < size; k++)
				{
					char tmp = left[k];   /* 暂存 left 的第 k 个字节 */
					left[k] = right[k];   /* 把 right 的第 k 个字节搬到 left */
					right[k] = tmp;       /* 把暂存的值写回 right */
				}

				swapped = 1;   /* 记录：本趟发生过交换 */
			}
		}

		/* 优化：一整趟扫下来一次交换都没有，
		 * 说明每个相邻元素都满足"左边 <= 右边"，整个数组已经有序，
		 * 再继续跑后面的趟也是白跑，直接提前收工。
		 * （没这个判断也能排对，只是已经有序的数组也要白跑 nmemb-1 趟） */
		if (swapped == 0)
		{
			break;
		}
	}
}

/* ------------------------------------------------------------
 * 测试 1：int 数组
 * 打印函数只是为了人工检查结果，不属于排序逻辑本身。
 * ------------------------------------------------------------ */
void print_int(const int *arr, int n)
{
	int i;
	for (i = 0; i < n; i++)
	{
		printf("%d ", arr[i]);   /* 每个数后面跟一个空格，最后换行 */
	}
	printf("\n");
}

/* ------------------------------------------------------------
 * 测试 2：结构体数组
 * 同一个 bubble_sort 不改一行代码，也能排结构体，
 * 只要再提供一个"懂结构体"的比较函数。
 * ------------------------------------------------------------ */
typedef struct Student
{
	char name[20];   /* 姓名 */
	int age;         /* 年龄 */
	float score;     /* 成绩 */
} Student;

int cmp_student_by_age(const void *a, const void *b)
{
	/* 回调传进来的一定是"某个元素的首地址"，
	 * 但它被 void* 包着，必须先转回 Student* 才能用 -> 访问成员。
	 * 加 const 表示"只读原数据"，排序过程只比较、不修改。 */
	const Student *x = (const Student *)a;
	const Student *y = (const Student *)b;

	if (x->age != y->age)
	{
		/* 年龄不同：按年龄升序（同样是防溢出的写法，
		 * 虽然 age 一般不会溢出，保持和 cmp_int 一致的套路） */
		return (x->age > y->age) - (x->age < y->age);
	}

	/* 年龄相同：再按姓名字典序排，
	 * 这样相同年龄的学生前后顺序是固定的，不会因为排序而变化
	 * （这叫"稳定"，实际项目里经常有这种要求） */
	return strcmp(x->name, y->name);
}

void print_students(const Student *stu, int n)
{
	int i;
	for (i = 0; i < n; i++)
	{
		/* %-8s：左对齐占 8 列；%3d：右对齐占 3 列；
		 * %5.1f：总宽 5 列、保留 1 位小数 */
		printf("%-8s  %3d  %5.1f\n", stu[i].name, stu[i].age, stu[i].score);
	}
}

int main(void)
{
	/* ---------- 测试 1：int 数组 ---------- */
	/* 故意打乱的一组数，方便肉眼检查排序前后 */
	int arr[] = { 9, 3, 7, 1, 5, 8, 2, 6, 4, 0 };

	/* 计算元素个数的惯用写法：
	 * sizeof(arr)    = 整个数组占的总字节数（10 个 int = 40）
	 * sizeof(arr[0]) = 单个元素占的字节数（1 个 int = 4）
	 * 相除 = 元素个数。
	 * 注意：只有当 arr 是"数组本身"时这个技巧才成立，
	 * 如果 arr 已经是指针（传进函数后的形参），sizeof 就失效了——
	 * 这也是为什么函数的数组参数总是要另外传一个长度。 */
	int n = (int)(sizeof(arr) / sizeof(arr[0]));

	printf("=== 1. int 数组 ===\n");
	printf("排序前：");
	print_int(arr, n);

	/* 调用通用排序：
	 *   arr            —— 数组名做参数时自动退化成首元素地址 &arr[0]
	 *   n              —— 元素个数 10
	 *   sizeof(arr[0]) —— 每个元素 4 字节
	 *   cmp_int        —— 比较函数名就是函数地址，直接传即可 */
	bubble_sort(arr, n, sizeof(arr[0]), cmp_int);

	printf("排序后：");
	print_int(arr, n);

	/* ---------- 测试 2：结构体数组 ---------- */
	/* 同一套 bubble_sort，换成结构体和对应的比较函数就能排 */
	Student stu[] =
	{
		{ "张三", 20, 92.5f },
		{ "李四", 18, 88.0f },
		{ "王五", 22, 76.5f },
		{ "赵六", 19, 95.0f },
		{ "孙七", 21, 81.0f }
	};
	int m = (int)(sizeof(stu) / sizeof(stu[0]));   /* 5 个学生 */

	printf("\n=== 2. 结构体数组（按年龄升序）===\n");
	printf("排序前：\n");
	print_students(stu, m);

	/* 关键在最后一个参数：换成了"按年龄比较"的函数，
	 * 排序函数一个字没改——"怎么比"完全由调用者决定 */
	bubble_sort(stu, m, sizeof(stu[0]), cmp_student_by_age);

	printf("排序后：\n");
	print_students(stu, m);

	/* ---------- 测试 3：和标准库 qsort 对比 ---------- */
	/* 验证思路：
	 * qsort 是标准库实现、久经考验的版本，
	 * 用同样的数据和同样的比较函数排一份副本，
	 * 再按字节比较两边的结果——完全一致就说明我们的实现可信。 */
	{
		/* 用和测试 1 完全相同的数据，保证对比公平 */
		int arr2[] = { 9, 3, 7, 1, 5, 8, 2, 6, 4, 0 };

		/* qsort 的用法和 bubble_sort 一模一样：
		 * 首地址、元素个数、单个大小、比较函数 */
		qsort(arr2, n, sizeof(arr2[0]), cmp_int);

		printf("\n=== 3. 与 qsort 对比 ===\n");

		/* memcmp 按字节比较两块内存：
		 * 返回 0 表示前面 sizeof(arr) 个字节完全相同
		 * （排好序的 int 数组，字节一样就代表数值一样） */
		if (memcmp(arr, arr2, sizeof(arr)) == 0)
		{
			printf("两种排序结果完全一致！\n");
		}
		else
		{
			printf("结果不一致，检查实现！\n");
		}
	}

	return 0;
}
