#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

/*
 * MAX 一身兼两职：
 *   1) 杨辉三角最多打印几行；
 *   2) 二维数组的第二维尺寸（编译器必须知道这一维，才知道数组元素之间隔多远）。
 *
 * 为什么用宏而不是普通变量？因为定义数组时中括号里必须是"编译期常量"，
 * 宏在预处理阶段就被替换成 8，正好满足这个要求；
 * 写成 int MAX = 8; 再拿它当数组维度，编译器多半会翻脸告诉你"不是常量表达式"。
 *
 * 好处：以后想改行数，只改这一处，下面所有用到 MAX 的地方自动跟着变。
 */
#define MAX 8

/*
 * 函数名：yanghui
 * 作用　：把杨辉三角的前 n 行算出来，存进 arr 这个二维数组里（只负责算，不负责打印）
 * 参数　：n   —— 要算几行，取值范围 1 ~ MAX
 *         arr —— 二维数组。形参写成 int (*arr)[MAX]，读作
 *                "指向【MAX 个 int 组成的数组】的指针"，也叫"行指针"。
 *
 *         ? 必背结论：二维数组传参，第一维可以省，第二维必须写！
 *           因为 arr[i][j] 在编译器眼里是 *(*(arr + i) + j)，
 *           arr + i 需要往后跳 i * MAX 个 int，第二维不写，编译器就算不出步长，直接报错：
 *             error: array type has incomplete element type 'int[]'
 *           反过来，行数只在 main 里用于分配内存，函数内部根本用不到，所以第一维可以空着。
 *
 * 返回　：无
 */
void yanghui(int n, int (*arr)[MAX])
{
	/* i 是行号，从 0 开始数。
	   为什么从 0 起、而不是从 2 起？看下面内层注释最后那一段。 */
	for (int i = 0; i < n; i++)
	{
		/* 杨辉三角第 i 行正好有 i + 1 个数，所以 j 从 0 数到 i（含 i）。
		   写成 j <= i 或 j < i + 1 都行，前者更直白一点。 */
		for (int j = 0; j <= i; j++)
		{
			/* 每行的第一个数（j == 0）和最后一个数（j == i）永远是 1。 */
			if (j == 0 || j == i)
			{
				arr[i][j] = 1;
			}
			else
			{
				/* 中间的数 = 上一行"左肩"那个 + 上一行"正上方"那个。
				   这是杨辉三角最核心的规律。
				   注意：这里只读 arr[i - 1] 那一行，所以必须"从上往下、从左往右"算，
				   外层 i 递增、内层 j 递增，天然满足这个前提。 */
				arr[i][j] = arr[i - 1][j - 1] + arr[i - 1][j];
			}
		}
	}

	/* 回头说前面那个问题：i = 0 时 j 只能取 0，走 if 分支得 1；
	   i = 1 时 j 取 0 和 1，也走 if 分支都得 1。
	   所以【前两行根本不用在循环外面提前硬写】——边界判断本身就覆盖了它俩。
	   旧版本里 arr[0][0] / arr[1][0] / arr[1][1] 那三行赋值可以整段删掉，
	   删掉之后还有个附带好处：n 传 1 的时候也不会再往 arr[1] 那一行写东西了。 */
}

/*
 * 函数名：print_yanghui
 * 作用　：把 arr 里存的前 n 行，按三角形的样子打印到屏幕上
 * 参数　：n   —— 打印几行
 *         arr —— 同上，行指针
 * 返回　：无
 *
 * 把"算"和"打"拆成两个函数的意义：以后想换个打印样式（比如右对齐、加空格、
 * 或者干脆写到文件里），只动这一个函数，算法那部分一行都不用碰。
 */
void print_yanghui(int n, int (*arr)[MAX])
{
	for (int i = 0; i < n; i++)
	{
		/* 每行只打印 i + 1 个数。
		   如果这里手滑写成 j < MAX，每行都会打满 MAX 个数，
		   三角形就会变成一个歪掉的矩形——这是新手最常踩的坑之一。 */
		for (int j = 0; j <= i; j++)
		{
			/* 把 %-4d 拆开看：
			     d  —— 按十进制整数打印；
			     4  —— 每个数至少占 4 个字符宽（不够就用空格补）；
			     -  —— 左对齐。不加负号是右对齐，三角形会歪向右边。
			   为什么非得带宽度？如果只写 "%d"，
			   第 6 行的 1 5 10 10 5 1 会被打印成 15101051，
			   六个数字连成一条数字虫，人眼根本分不出边界。
			   加上宽度后每个数占满 4 格，行行对齐，才看得出是三角形。 */
			printf("%-4d", arr[i][j]);
		}
		printf("\n");   /* 一行打完了，换行，接着打下一行 */
	}
}

int main(void)
{
	/* int main(void) 里的 void 表示"这个程序不接收命令行参数"。
	   写 int main() 也不算错，但 (void) 更严谨，是 C 语言的推荐写法。 */

	/* = { 0 } 的作用：把二维数组里每一个元素都初始化成 0。
	   不加的话，数组里装的是内存中残留的垃圾值。
	   虽然本程序不会读到没赋值的格子（只打印三角区域，属于"运气好"），
	   但养成初始化的习惯，能避免以后改代码时"莫名其妙算出个天文数字"这种事故。 */
	int arr[MAX][MAX] = { 0 };

	/* 想改成"让用户自己输行数"的话，就改下面这一行的 n，
	   例如：scanf("%d", &n);
	   但一定要检查 n 是否落在 1 ~ MAX 之间——数组只有 MAX 行，
	   n 大于 MAX 就会写越界，那是真会把程序写崩的。 */
	int n = MAX;

	yanghui(n, arr);          /* 第一步：算——把三角填进数组（只管算，不管看） */
	print_yanghui(n, arr);    /* 第二步：画——把数组按三角形打出来（只管看，不管算） */

	return 0;
}
